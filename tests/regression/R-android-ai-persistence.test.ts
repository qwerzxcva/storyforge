import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'

async function freshStore() {
  vi.resetModules()
  return (await import('../../src/stores/ai-config')).useAIConfigStore
}
beforeEach(() => { localStorage.clear(); sessionStorage.clear() })
afterEach(() => { vi.unstubAllEnvs(); localStorage.clear(); sessionStorage.clear() })
const headers = [{ name: 'X-Test', value: 'synthetic-header' }]

describe('Android AI credential persistence', () => {
  it('remembers Android credentials and presets across a cold start', async () => {
    vi.stubEnv('MODE', 'android')
    let store = await freshStore()
    expect(store.getState().rememberApiKey).toBe(true)
    store.getState().setConfig({ provider: 'custom', baseUrl: 'https://one.invalid/v1', apiKey: 'synthetic-one', customHeaders: headers })
    const id = store.getState().saveAsPreset('one')
    sessionStorage.clear()
    store = await freshStore()
    expect(store.getState().config).toMatchObject({ apiKey: 'synthetic-one', customHeaders: headers })
    store.getState().applyPreset(id)
    expect(store.getState().config.apiKey).toBe('synthetic-one')
  })
  it('upgrades an old Android false once, then respects an explicit opt-out', async () => {
    vi.stubEnv('MODE', 'test')
    const old = await freshStore()
    old.getState().setConfig({ provider: 'custom', baseUrl: 'https://one.invalid/v1', apiKey: 'synthetic-one', customHeaders: headers })
    const id = old.getState().saveAsPreset('old')
    vi.stubEnv('MODE', 'android')
    let store = await freshStore()
    expect(store.getState().rememberApiKey).toBe(true)
    sessionStorage.clear()
    store = await freshStore()
    store.getState().applyPreset(id)
    expect(store.getState().config).toMatchObject({ apiKey: 'synthetic-one', customHeaders: headers })
    store.getState().setRememberApiKey(false)
    sessionStorage.clear()
    store = await freshStore()
    expect(store.getState().rememberApiKey).toBe(false)
    expect(store.getState().config.apiKey).toBe('')
    expect(store.getState().config.customHeaders ?? []).toEqual([])
  })
  it('migrates all preset keys and headers in both directions without crossing hosts', async () => {
    vi.stubEnv('MODE', 'test')
    let store = await freshStore()
    expect(store.getState().rememberApiKey).toBe(false)
    store.getState().setConfig({ provider: 'custom', baseUrl: 'https://one.invalid/v1', apiKey: 'synthetic-one', customHeaders: headers })
    const one = store.getState().saveAsPreset('one')
    store.getState().setConfig({ baseUrl: 'https://two.invalid/v1', apiKey: 'synthetic-two', customHeaders: [{ name: 'X-Test', value: 'synthetic-two-header' }] })
    const two = store.getState().saveAsPreset('two')
    store.getState().setRememberApiKey(true)
    sessionStorage.clear()
    store = await freshStore()
    store.getState().applyPreset(one)
    expect(store.getState().config).toMatchObject({ apiKey: 'synthetic-one', customHeaders: headers })
    store.getState().setRememberApiKey(false)
    expect(localStorage.getItem('storyforge-ai-presets')).not.toContain('synthetic-')
    store = await freshStore()
    store.getState().applyPreset(two)
    expect(store.getState().config).toMatchObject({ apiKey: 'synthetic-two', customHeaders: [{ name: 'X-Test', value: 'synthetic-two-header' }] })
    store.getState().applyPreset(one)
    expect(store.getState().config.apiKey).toBe('synthetic-one')
  })
})
